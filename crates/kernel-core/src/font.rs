//! 8x8 bitmap font for text rendering (V0.5).
//!
//! Printable ASCII 0x20–0x7E from the public-domain `font8x8` basic set
//! (Marcel Sondaar / Daniel Hepper). Each glyph is 8 bytes, one per row
//! top→bottom; within a row bit 0 (LSB) is the leftmost pixel. Pure data +
//! lookup, so glyph geometry is host-unit-testable and the kernel renderer
//! reuses it unchanged.

pub const GLYPH_WIDTH: usize = 8;
pub const GLYPH_HEIGHT: usize = 8;

const FIRST: u8 = 0x20;
const LAST: u8 = 0x7E;

/// Glyph bitmap for a byte, or the '?' glyph for anything outside the set.
pub fn glyph(c: u8) -> &'static [u8; 8] {
    if (FIRST..=LAST).contains(&c) {
        &FONT[(c - FIRST) as usize]
    } else {
        &FONT[(b'?' - FIRST) as usize]
    }
}

/// True if pixel (col,row) of the glyph for `c` is set.
pub fn pixel(c: u8, col: usize, row: usize) -> bool {
    if col >= GLYPH_WIDTH || row >= GLYPH_HEIGHT {
        return false;
    }
    glyph(c)[row] & (1 << col) != 0
}

