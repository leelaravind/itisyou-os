#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn space_is_blank_capital_a_is_not() {
        assert!(glyph(b' ').iter().all(|&r| r == 0));
        assert!(glyph(b'A').iter().any(|&r| r != 0));
    }

    #[test]
    fn out_of_range_falls_back_to_question_mark() {
        assert_eq!(glyph(0x01), glyph(b'?'));
        assert_eq!(glyph(0xFF), glyph(b'?'));
    }

    #[test]
    fn pixel_lookup_matches_glyph_bits() {
        // Row 0 of 'A' is 0x0C = bits 2,3 set.
        assert!(pixel(b'A', 2, 0));
        assert!(pixel(b'A', 3, 0));
        assert!(!pixel(b'A', 0, 0));
        assert!(!pixel(b'A', 8, 0)); // out of bounds
        assert!(!pixel(b'A', 0, 8));
    }

    #[test]
    fn all_glyphs_present() {
        assert_eq!(FONT.len(), (LAST - FIRST + 1) as usize);
    }
}
